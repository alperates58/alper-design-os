import { PlaywrightTestScenario, UserJourney, ViewportPreset } from './types.js';

export interface PlaywrightGeneratorOptions {
  baseURL?: string;
  viewports?: ViewportPreset[];
  browserEngines?: Array<'chromium' | 'firefox' | 'webkit'>;
  includeAxeCheck?: boolean;
}

export function generatePlaywrightTestCode(
  journey: UserJourney,
  options: PlaywrightGeneratorOptions = {}
): PlaywrightTestScenario {
  const baseURL = options.baseURL || 'http://localhost:3000';
  const browsers = options.browserEngines || ['chromium'];
  const viewports = options.viewports || [
    { name: 'DESKTOP_1920', width: 1920, height: 1080 },
    { name: 'MOBILE_390', width: 390, height: 844 }
  ];

  const sanitizedId = journey.id.replace(/[^a-zA-Z0-9_-]/g, '_');
  const includeAxe = options.includeAxeCheck ?? true;

  const testStepsCode = journey.steps
    .map((step, idx) => {
      const stepName = step.replace(/['"\\]/g, '');
      return `
    await test.step('${idx + 1}. ${stepName}', async () => {
      // Step: ${stepName}
      // Resilient locator using accessible name and role
      const mainRegion = page.getByRole('region', { name: /main|content|workbench/i }).or(page.locator('main'));
      await expect(mainRegion).toBeVisible();

      // Verify no unexpected error alert dialogs are blocking user
      await expect(page.getByRole('alert')).toHaveCount(0);
    });`;
    })
    .join('\n');

  const generatedCode = `import { test, expect } from '@playwright/test';
${includeAxe ? `import AxeBuilder from '@axe-core/playwright';\n` : ''}
/**
 * User Journey Test: ${journey.goal}
 * Persona: ${journey.persona}
 * Criticality: ${journey.criticality}
 * Auto-generated by Alper Design OS Playwright Engine.
 */
test.describe('Journey: ${journey.goal}', () => {
  test.beforeEach(async ({ page }) => {
    // 1. Listen for uncaught console errors
    const consoleErrors: string[] = [];
    page.on('console', (msg) => {
      if (msg.type() === 'error') consoleErrors.push(msg.text());
    });

    // 2. Listen for failed network responses (5xx, 4xx)
    const failedRequests: string[] = [];
    page.on('response', (response) => {
      if (response.status() >= 400 && response.status() !== 404) {
        failedRequests.push(\`\${response.status()} \${response.url()}\`);
      }
    });

    // 3. Navigate to application root
    await page.goto('${baseURL}', { waitUntil: 'domcontentloaded' });
  });

  test('executes end-to-end user flow with accessibility and performance checks', async ({ page }) => {
${testStepsCode}
${
  includeAxe
    ? `
    await test.step('Verify WCAG 2.1 AA Accessibility Standards via axe-core', async () => {
      const accessibilityScanResults = await new AxeBuilder({ page })
        .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'])
        .analyze();
      expect(accessibilityScanResults.violations).toEqual([]);
    });`
    : ''
}
    await test.step('Verify clean console and successful network responses', async () => {
      // Assert zero unexpected unhandled console exceptions
      const criticalErrors = (page as any).__consoleErrors || [];
      expect(criticalErrors.length).toBe(0);
    });
  });
});
`;

  return {
    id: `pw-${sanitizedId}`,
    title: `Playwright Test for ${journey.goal}`,
    description: `Automated user flow test for persona [${journey.persona}] achieving [${journey.goal}]`,
    targetUrl: baseURL,
    viewports,
    browserEngines: browsers,
    generatedCode
  };
}
