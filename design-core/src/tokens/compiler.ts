import { CompiledTokenOutput, DTCGToken, DTCGTokenFile, TokenOutputFormat } from './schema.js';

export interface FlattenedToken {
  path: string[];
  name: string;
  value: string | number;
  type?: string;
  description?: string;
}

export function flattenDTCGTokens(obj: DTCGTokenFile, currentPath: string[] = []): FlattenedToken[] {
  const tokens: FlattenedToken[] = [];

  for (const [key, val] of Object.entries(obj)) {
    if (key.startsWith('$')) {
      continue;
    }

    if (val && typeof val === 'object') {
      if ('$value' in val) {
        const token = val as DTCGToken;
        const fullPath = [...currentPath, key];
        tokens.push({
          path: fullPath,
          name: fullPath.join('-'),
          value: typeof token.$value === 'object' ? JSON.stringify(token.$value) : token.$value,
          type: token.$type,
          description: token.$description
        });
      } else {
        tokens.push(...flattenDTCGTokens(val as DTCGTokenFile, [...currentPath, key]));
      }
    }
  }

  return tokens;
}

export class TokenCompiler {
  private tokens: FlattenedToken[];

  constructor(tokenFiles: DTCGTokenFile[]) {
    this.tokens = tokenFiles.flatMap((file) => flattenDTCGTokens(file));
  }

  public compile(format: TokenOutputFormat): CompiledTokenOutput {
    switch (format) {
      case 'css':
        return this.compileToCss();
      case 'scss':
        return this.compileToScss();
      case 'typescript':
        return this.compileToTypeScript();
      case 'tailwind-json':
        return this.compileToTailwindTheme();
      default:
        throw new Error(`Unsupported token output format: ${format}`);
    }
  }

  public compileAll(): CompiledTokenOutput[] {
    return [
      this.compile('css'),
      this.compile('scss'),
      this.compile('typescript'),
      this.compile('tailwind-json')
    ];
  }

  private compileToCss(): CompiledTokenOutput {
    const lines = [
      '/**',
      ' * ALPER DESIGN OS - Compiled Design Tokens (CSS Custom Properties)',
      ' * DTCG Specification Compliant (https://design-tokens.github.io/community-group/format/)',
      ' * Auto-generated by TokenCompiler. Do not edit directly.',
      ' */',
      ':root {'
    ];

    for (const t of this.tokens) {
      const desc = t.description ? ` /* ${t.description} */` : '';
      lines.push(`  --${t.name}: ${t.value};${desc}`);
    }

    lines.push('}');
    return {
      format: 'css',
      filename: 'tokens.css',
      content: lines.join('\n')
    };
  }

  private compileToScss(): CompiledTokenOutput {
    const lines = [
      '// ALPER DESIGN OS - Compiled Design Tokens (SCSS Variables)',
      '// DTCG Specification Compliant',
      '// Auto-generated by TokenCompiler. Do not edit directly.'
    ];

    for (const t of this.tokens) {
      const desc = t.description ? ` // ${t.description}` : '';
      lines.push(`$${t.name}: ${t.value};${desc}`);
    }

    return {
      format: 'scss',
      filename: '_tokens.scss',
      content: lines.join('\n')
    };
  }

  private compileToTypeScript(): CompiledTokenOutput {
    const tokenTree: Record<string, unknown> = {};

    for (const t of this.tokens) {
      let current: any = tokenTree;
      for (let i = 0; i < t.path.length; i++) {
        const segment = t.path[i]!;
        if (i === t.path.length - 1) {
          current[segment] = t.value;
        } else {
          current[segment] = current[segment] || {};
          current = current[segment];
        }
      }
    }

    const lines = [
      '/**',
      ' * ALPER DESIGN OS - Compiled Design Tokens (TypeScript Constants)',
      ' * Auto-generated by TokenCompiler. Do not edit directly.',
      ' */',
      `export const designTokens = ${JSON.stringify(tokenTree, null, 2)} as const;`,
      '',
      'export type DesignTokens = typeof designTokens;'
    ];

    return {
      format: 'typescript',
      filename: 'tokens.ts',
      content: lines.join('\n')
    };
  }

  private compileToTailwindTheme(): CompiledTokenOutput {
    const colors: Record<string, string> = {};
    const spacing: Record<string, string> = {};
    const borderRadius: Record<string, string> = {};

    for (const t of this.tokens) {
      if (t.path[0] === 'color') {
        const key = t.path.slice(1).join('-');
        colors[key] = `var(--${t.name}, ${t.value})`;
      } else if (t.path[0] === 'spacing') {
        const key = t.path.slice(1).join('-');
        spacing[key] = `var(--${t.name}, ${t.value})`;
      } else if (t.path[0] === 'radius') {
        const key = t.path.slice(1).join('-');
        borderRadius[key] = `var(--${t.name}, ${t.value})`;
      }
    }

    const tailwindTheme = {
      theme: {
        extend: {
          colors,
          spacing,
          borderRadius
        }
      }
    };

    return {
      format: 'tailwind-json',
      filename: 'tailwind-tokens.json',
      content: JSON.stringify(tailwindTheme, null, 2)
    };
  }
}
